import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { BANK } from '../problems-src/bank.mjs';

const OUTPUT = fileURLToPath(new URL('../js/data/runnable.js', import.meta.url));
const INDEX = fileURLToPath(new URL('../js/data/runnable-index.js', import.meta.url));
const RANDOM_TESTS = 22;

function rng(seed) {
  let a = seed >>> 0;
  const next = () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const r = {
    int: (lo, hi) => lo + Math.floor(next() * (hi - lo + 1)),
    chance: (p) => next() < p,
    pick: (list) => list[Math.floor(next() * list.length)],
    shuffle: (list) => {
      const copy = [...list];
      for (let i = copy.length - 1; i > 0; i--) {
        const j = Math.floor(next() * (i + 1));
        [copy[i], copy[j]] = [copy[j], copy[i]];
      }
      return copy;
    },
    word: (length, alphabet) => Array.from({ length: Math.max(0, length) }, () => alphabet[Math.floor(next() * alphabet.length)]).join(''),
    pair: (n) => {
      const i = Math.floor(next() * n);
      let j = Math.floor(next() * (n - 1));
      if (j >= i) j += 1;
      return [i, j];
    },
  };
  return r;
}

function seedFor(id) {
  let h = 2166136261;
  for (const c of id) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return h >>> 0;
}

const clone = (value) => JSON.parse(JSON.stringify(value));

export function buildProblems() {
  return BANK.map((problem) => {
    const r = rng(seedFor(problem.id));
    const make = (args, kind) => ({ args: clone(args), expected: problem.solve(...clone(args)), kind });
    const examples = problem.examples.map((args) => make(args, 'example'));
    const tests = [
      ...problem.edge.map((args) => make(args, 'edge')),
      ...Array.from({ length: RANDOM_TESTS }, () => make(problem.gen(r), 'random')),
      ...(problem.large ? [make(problem.large(r), 'large')] : []),
    ];
    return {
      id: problem.id,
      title: problem.title,
      difficulty: problem.difficulty,
      fn: problem.fn,
      params: problem.params,
      returns: problem.returns,
      compare: problem.compare || 'exact',
      statement: problem.statement,
      constraints: problem.constraints,
      examples,
      tests,
    };
  });
}

const HEADER = '// Generated by scripts/build-problems.mjs from problems-src/bank.mjs. Do not edit by hand.';

export function renderModule(problems) {
  return `${HEADER}\nexport const RUNNABLE = ${JSON.stringify(problems)};\n`;
}

export function renderIndex(problems) {
  return `${HEADER}\nexport const RUNNABLE_IDS = ${JSON.stringify(problems.map((problem) => problem.id))};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const problems = buildProblems();
  writeFileSync(OUTPUT, renderModule(problems));
  writeFileSync(INDEX, renderIndex(problems));
  console.log('wrote js/data/runnable.js and js/data/runnable-index.js');
}
